int	ft_atoi(char *src)
{
	long	nb;
	int	n;

	nb = 0;
	n = 0;
	while(*src == 32 || (*src >= 9 && *src <= 13))
		src++;
	while (*src == '-' || *src == '+')
	{
		if (*src == '-')
			n++;
		src++;
	}
	while (*src >= '0' && *src <= '9')
	{
		nb = (nb * 10) + *src - '0';
		src++;
	}
	if (n % 2 == 1)
		nb = -nb;
	return (nb);
}