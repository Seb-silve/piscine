#include <unistd.h>

int	main(int c, char **tab)
{
	int	i;
	int	j;
	
	i = 0;
	j = 1;
	
	while (j < c){
		while (tab[j][i])
		{
			write(1, &tab[j][i], 1);
			i++;
		}
		i = 0;
		j++;
		write(1, "\n", 1);
}
	return (0);
}